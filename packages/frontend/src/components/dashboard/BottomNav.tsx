export function BottomNav() {
  const pathname = usePathname();

  return (
    <nav
      className="fixed bottom-0 left-0 right-0 z-50 flex md:hidden border-t border-white/10 bg-black pb-[env(safe-area-inset-bottom)]"
      style={{ height: "calc(64px + env(safe-area-inset-bottom))" }}
    >
      {navItems.map(({ href, label, Icon }) => {
        const isActive =
          pathname === href || (href !== "/dashboard" && pathname.startsWith(href));
        return (
          <Link
            key={href}
            href={href}
            className={`flex min-h-[44px] flex-1 flex-col items-center justify-center gap-1 text-xs transition-colors ${
              isActive ? "text-emerald-400" : "text-gray-400 hover:text-white"
            }`}
          >
            <Icon className="h-5 w-5" />
            <span>{label}</span>
          </Link>
        );
      })}
    </nav>
  );
}
